/**
 * Writes src/content/media-sizes.ts: the natural pixel size of every picture listed in
 * src/content/media.ts, keyed by slot name. Artwork reads it so a lazy <img> carries real
 * width/height attributes, which is what lets the browser reserve the box before the bytes
 * arrive instead of shifting the page when they land.
 *
 *   node scripts/media-sizes.mjs
 *
 * Run it again after adding or replacing pictures in public/media. Sizes are read from the
 * file headers, not decoded, so this works with no image library.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = process.cwd();
const mediaFile = path.join(root, "src/content/media.ts");
const out = path.join(root, "src/content/media-sizes.ts");

/** JPEG: walk the marker segments until a start-of-frame; PNG/SVG/WebP/GIF: read the header. */
function dims(buf) {
  if (buf.length > 8 && buf.readUInt32BE(0) === 0x89504e47) return [buf.readUInt32BE(16), buf.readUInt32BE(20)];
  if (buf.length > 10 && buf.toString("latin1", 0, 6) === "GIF89a") return [buf.readUInt16LE(6), buf.readUInt16LE(8)];
  if (buf.length > 30 && buf.toString("latin1", 0, 4) === "RIFF" && buf.toString("latin1", 8, 12) === "WEBP") {
    const chunk = buf.toString("latin1", 12, 16);
    if (chunk === "VP8L") {
      const b = buf.readUInt32LE(20);
      return [(b & 0x3fff) + 1, ((b >> 14) & 0x3fff) + 1];
    }
    if (chunk === "VP8X") return [buf.readUIntLE(24, 3) + 1, buf.readUIntLE(27, 3) + 1];
    if (chunk === "VP8 ") {
      const w = buf.readUInt16LE(26) & 0x3fff;
      const h = buf.readUInt16LE(28) & 0x3fff;
      return [w, h];
    }
    return null;
  }
  if (buf.slice(0, 4).toString() === "<svg") {
    const m = /width="(\d+(?:\.\d+)?)"[^>]*height="(\d+(?:\.\d+)?)/.exec(buf.toString("utf8").slice(0, 400));
    return m ? [Math.round(+m[1]), Math.round(+m[2])] : null;
  }
  let i = 2;
  while (i + 4 <= buf.length) {
    if (buf[i] !== 0xff) { i += 1; continue; }
    const marker = buf[i + 1];
    if (marker >= 0xc0 && marker <= 0xcf && marker !== 0xc4 && marker !== 0xc8 && marker !== 0xcc) {
      return [buf.readUInt16BE(i + 7), buf.readUInt16BE(i + 9)];
    }
    if (marker === 0xff || marker === 0x00 || marker === 0x01) { i += 1; continue; }
    i += 2 + buf.readUInt16BE(i + 2);
  }
  return null;
}

const source = readFileSync(mediaFile, "utf8");
const slots = [...source.matchAll(/"([^"]+)":\s*"([^"]+)"/g)].map((m) => [m[1], m[2]]);

const lines = [];
let missing = 0;
for (const [name, url] of slots) {
  const file = path.join(root, "public", url);
  let size = null;
  try {
    size = dims(readFileSync(file));
  } catch {
    missing += 1;
  }
  if (!size) {
    missing += 1;
    console.warn(`no readable size for ${name} -> ${url}`);
    continue;
  }
  lines.push(`  ${JSON.stringify(name)}: [${size[0]}, ${size[1]}],`);
}

const body = `/**
 * Generated by scripts/media-sizes.mjs -- the natural size of each picture in media.ts, in
 * pixels. Do not edit by hand: rerun the script after the pictures change. A slot missing
 * here is a slot whose file is not on disk yet, and Artwork draws it as a gradient anyway.
 */
export const mediaSizes: Record<string, [number, number]> = {
${lines.join("\n")}
};
`;
writeFileSync(out, body);
console.log(`wrote ${out}: ${lines.length} slots, ${missing} without a readable file`);
